func TestCanonicalLineCatalogRecognizesSPKFinancialStatementRows(t *testing.T) {
	cases := []struct {
		input      string
		code       string
		normalized string
		statement  string
	}{
		{"Satış Amaçlı Sınıflandırılan Duran Varlıklar", "1AJ", "assets_held_for_sale", StatementBalanceSheet},
		{"Özkaynak Yöntemiyle Değerlenen Yatırımların Kar/Zararlarındaki Paylar", "3HAC", "share_of_profit_loss_from_equity_method_investments", StatementIncome},
		{"Ana Ortaklık Payları", "3Z", "parent_net_income", StatementIncome},
		{"İşletme Faaliyetlerinden Kaynaklanan Nakit Akışları", "4C", "operating_cash_flow", StatementCashFlow},
		{"Peşin Ödenmiş Giderler", "", "prepaid_expenses", StatementBalanceSheet},
	}
	for _, tc := range cases {
		got, ok := CanonicalLineDefinitionForText(tc.input)
		if !ok {
			t.Fatalf("expected canonical line for %q", tc.input)
		}
		if got.Code != tc.code || got.Normalized != tc.normalized || got.StatementType != tc.statement {
			t.Fatalf("%q mapped to %+v, want code=%q normalized=%q statement=%q", tc.input, got, tc.code, tc.normalized, tc.statement)
		}
	}
}

func TestCanonicalLineCatalogUsesSectionContextForRepeatedSPKRows(t *testing.T) {
	cases := []struct {
		input      string
		context    string
		code       string
		normalized string
	}{
		{"Ticari Alacaklar", "Dönen Varlıklar", "1AC", "short_term_trade_receivables"},
		{"Ticari Alacaklar", "Duran Varlıklar", "1B", "long_term_trade_receivables"},
		{"Finansal Yatırımlar", "Dönen Varlıklar", "1AB", "short_term_financial_investments"},
		{"Finansal Yatırımlar", "Duran Varlıklar", "1BC", "long_term_financial_investments"},
		{"Ticari Borçlar", "Kısa Vadeli Yükümlülükler", "2AAGAA", "short_term_trade_payables"},
		{"Ticari Borçlar", "Uzun Vadeli Yükümlülükler", "2BBA", "long_term_trade_payables"},
		{"Ticari Alacaklar", "credit_risk_table", "", "credit_risk_trade_receivables"},
		{"Ticari Borçlar", "liquidity_risk_table", "", "liquidity_trade_payables"},
		{"Ticari Alacaklar", "fx_position_table", "", "fx_trade_receivables"},
		{"Özkaynaklar", "fx_sensitivity_table", "", "fx_sensitivity_equity_column"},
		{"Finansal Borçlar", "portfolio_limits_table", "", "portfolio_financial_debt"},
	}
	for _, tc := range cases {
		got, ok := CanonicalLineDefinitionForTextInContext(tc.input, tc.context)
		if !ok {
			t.Fatalf("expected contextual canonical line for %q in %q", tc.input, tc.context)
		}
		if got.Code != tc.code || got.Normalized != tc.normalized {
			t.Fatalf("%q in %q mapped to %+v, want code=%q normalized=%q", tc.input, tc.context, got, tc.code, tc.normalized)
		}
	}
}

