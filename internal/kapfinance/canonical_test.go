func TestBuildBilancoMapsKAPFactsToCanonicalFinancials(t *testing.T) {
	info, summary := BuildBilanco(BuildOptions{
		Ticker:      "TEST",
		GeneratedAt: time.Date(2026, 6, 17, 12, 0, 0, 0, time.UTC),
	}, []Fact{
		{ID: "assets", Ticker: "TEST", Period: "2025/12", LineItemNormalized: "total_assets", Value: 12_500, Currency: "TRY", Unit: "thousand_try", Confidence: 0.91, CertificationStatus: "certified", CertificationAnalysisUsable: true, SourceTableID: "tbl1", DocumentDate: "2026-02-20"},
		{ID: "equity", Ticker: "TEST", Period: "2025-Q4", LineItemNormalized: "Özkaynaklar", Value: 7_000, Currency: "TRY", Unit: "thousand_try", Confidence: 0.9, CertificationStatus: "certified", CertificationAnalysisUsable: true, SourceTableID: "tbl1", DocumentDate: "2026-02-20"},
		{ID: "revenue", Ticker: "TEST", Period: "12AB", FiscalYear: 2025, LineItemNormalized: "Hasılat", Value: 4_200, Currency: "TRY", Unit: "thousand_try", Confidence: 0.88, ValidationStatus: "valid", SourceTableID: "tbl2", DocumentDate: "2026-02-20"},
	})
	if info == nil {
		t.Fatalf("expected bilanco info, summary=%+v", summary)
	}
	if summary.FactsAccepted != 3 {
		t.Fatalf("accepted facts=%d, want 3", summary.FactsAccepted)
	}
	assertFieldValue(t, info.Data["1BL"].Years["2025"][0], 12_500_000)
	assertFieldValue(t, info.Data["2N"].Years["2025"][0], 7_000_000)
	assertFieldValue(t, info.Data["3C"].Years["2025"][0], 4_200_000)
	if info.Periods["2025-Q4"].AvailableAt == nil {
		t.Fatalf("expected conservative available_at from document date")
	}
}

