func inferTalibTemplate(name string) string {
	if hasAny(name, "adx", "adxr", "apo", "aroon", "bop", "cci", "cmo", "dx", "macd", "mfi", "mom", "ppo", "roc", "rsi", "stoch", "trix", "ultosc", "willr") {
		return "momentum"
	}
	if hasAny(name, "ad", "adosc", "obv") {
		return "volume"
	}
	if hasAny(name, "atr", "natr", "trange") {
		return "volatility"
	}
	if hasAny(name, "beta", "correl", "linearreg", "stddev", "var") {
		return "statistical"
	}
	if hasAny(name, "avgprice", "medprice", "typprice", "wclprice") {
		return "price_transform"
	}
	if hasAny(name, "ht_") {
		return "cycle"
	}
	return "moving_average"
}

func normalize(value string) string {
	value = strings.ToLower(value)
	value = strings.ReplaceAll(value, "-", " ")
	value = strings.ReplaceAll(value, "_", " ")
	value = strings.ReplaceAll(value, "%", " percent ")
	value = regexp.MustCompile(`\s+`).ReplaceAllString(value, " ")
	return strings.TrimSpace(value)
}

func hasAny(value string, needles ...string) bool {
	for _, needle := range needles {
		if strings.Contains(value, needle) {
			return true
		}
	}
	return false
}

