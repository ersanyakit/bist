package main

import (
	"fmt"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

type group struct {
	category string
	name     string
	items    string
}

type spec struct {
	Name       string
	Category   string
	Group      string
	Template   string
	Confidence float64
}

func main() {
	seen := map[string]bool{}
	specs := []spec{}
	for _, g := range catalog {
		for _, item := range splitItems(g.items) {
			key := strings.ToLower(item)
			if key == "" || seen[key] {
				continue
			}
			seen[key] = true
			specs = append(specs, spec{
				Name:       item,
				Category:   g.category,
				Group:      g.name,
				Template:   inferTemplate(g.category, item),
				Confidence: confidenceFor(g.category),
			})
		}
	}
	sort.Slice(specs, func(i, j int) bool { return specs[i].Name < specs[j].Name })
	outDir := filepath.Join("internal", "indicators", "generated")
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		log.Fatal(err)
	}
	var b strings.Builder
	b.WriteString("// Code generated by tools/indicator_catalog_gen; DO NOT EDIT.\n")
	b.WriteString("package generated\n\n")
	b.WriteString("func init() {\n")
	b.WriteString("\tSpecs = append(Specs,\n")
	for _, spec := range specs {
		b.WriteString(fmt.Sprintf("\t\tSpec{Name: %q, Category: %q, Group: %q, Template: %q, Confidence: %.2f},\n", spec.Name, spec.Category, spec.Group, spec.Template, spec.Confidence))
	}
	b.WriteString("\t)\n")
	b.WriteString("}\n")
	if err := os.WriteFile(filepath.Join(outDir, "catalog.go"), []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("generated %d indicator specs\n", len(specs))
}

func splitItems(value string) []string {
	parts := strings.Split(value, "|")
	out := make([]string, 0, len(parts))
	for _, part := range parts {
		part = strings.TrimSpace(part)
		if part != "" {
			out = append(out, part)
		}
	}
	return out
}

func confidenceFor(category string) float64 {
	switch category {
	case "trend", "momentum", "volume", "volatility", "support_resistance", "channel", "ichimoku", "fibonacci", "statistical", "price_transform", "stop", "divergence", "smart_money", "elliott", "wyckoff":
		return 0.62
	case "breadth", "sentiment", "order_flow", "options", "crypto_onchain":
		return 0.0
	default:
		return 0.55
	}
}

